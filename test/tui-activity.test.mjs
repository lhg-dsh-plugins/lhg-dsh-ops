import { createActivityStore } from '../lib/tui/activity.js'
import { call, result, dispatch } from './lib/activity-events.mjs'
import { assert, report, test } from './lib/harness.mjs'

await test('native events pair by opaque call ID and snapshots remain referentially stable', () => {
  const store = createActivityStore()
  const empty = store.snapshot('one')
  assert.equal(store.snapshot('one'), empty)
  assert.equal(store.observe('one', call(1, 'opaque-id')), true)
  const pending = store.snapshot('one')
  assert.equal(pending.total, 1); assert.equal(pending.running, 1)
  assert.equal(store.observe('one', result(2, 'opaque-id')), true)
  const settled = store.snapshot('one')
  assert.equal(settled.running, 0); assert.equal(settled.returned, 1)
  assert.equal(settled.recent[0].durationMs, 10)
  assert.equal(settled.recent[0].status, 'returned')
  assert.equal(pending.running, 1)
  assert.ok(Object.isFrozen(settled)); assert.ok(Object.isFrozen(settled.recent[0]))
  assert.equal(store.snapshot('one'), settled)
})
await test('transport return is neutral, not an invented claim of business success', () => {
  const store = createActivityStore()
  store.observe('one', call(1))
  store.observe('one', result(2, 'a', { status: 'rejected', error: { code: 'POLICY_DENIED' } }))
  assert.equal(store.snapshot('one').recent[0].status, 'returned')
  assert.equal(store.snapshot('one').recent[0].success, undefined)
})
await test('PTC counts only its actual OPS child calls, never the outer program or foreign tools', () => {
  const store = createActivityStore()
  store.observe('one', call(1, 'outer', 'run_code'))
  store.observe('one', dispatch(2, 'opaque/not-parsed', 'ops_glob'))
  store.observe('one', dispatch(3, 'foreign', 'ops_not_ours'))
  store.observe('one', dispatch(4, 'opaque/not-parsed', 'ops_glob', {}))
  store.observe('one', result(5, 'outer'))
  assert.equal(store.snapshot('one').total, 1)
  assert.equal(store.snapshot('one').returned, 1)
  assert.equal(store.snapshot('one').recent[0].id, 'opaque/not-parsed')
})
await test('host errors and message isError are observed without storing their text', () => {
  const store = createActivityStore()
  store.observe('one', call(1))
  store.observe('one', result(2, 'a', {}, { name: 'ToolError', code: 'NOPE', reason: 'secret' }))
  store.observe('one', call(3, 'b', 'ops_bash', { command: 'secret command' }))
  const returned = result(4, 'b'); returned.data.message.isError = true
  store.observe('one', returned)
  store.observe('one', dispatch(5, 'c'))
  store.observe('one', dispatch(6, 'c', 'ops_glob', {}, { code: 'ABORTED', reason: 'secret' }))
  assert.equal(store.snapshot('one').errors, 3)
  assert.equal(JSON.stringify(store.snapshot('one')).includes('secret'), false)
})
await test('sessions are isolated and observer state never retains arguments or output bodies', () => {
  const store = createActivityStore()
  store.observe('one', call(1, 'same', 'ops_grep', { pattern: 'PRIVATE_SEARCH' }))
  store.observe('two', call(1, 'same', 'ops_replace', { replacement: 'PRIVATE_REPLACEMENT' }))
  store.observe('one', result(2, 'same', { contents: 'PRIVATE_FILE' }))
  assert.equal(store.snapshot('two').running, 1)
  assert.equal(store.snapshot('two').returned, 0)
  assert.equal(JSON.stringify(store.snapshot('one')).includes('PRIVATE'), false)
  assert.equal(JSON.stringify(store.snapshot('two')).includes('PRIVATE'), false)
})
await test('duplicate and out-of-order events do not inflate counters', () => {
  const store = createActivityStore()
  store.observe('one', call(1)); store.observe('one', call(1)); store.observe('one', call(2))
  store.observe('one', result(3)); store.observe('one', result(3)); store.observe('one', call(1))
  assert.equal(store.snapshot('one').total, 1)
  assert.equal(store.snapshot('one').returned, 1)
})
await test('recent rows and retained sessions are bounded, including an LRU touch', () => {
  const store = createActivityStore({ recentLimit: 2, maxSessions: 2 })
  for (let i = 0; i < 3; i++) { store.observe('one', call(i * 2, String(i))); store.observe('one', result(i * 2 + 1, String(i))) }
  assert.equal(store.snapshot('one').total, 3)
  assert.deepEqual(store.snapshot('one').recent.map(row => row.id), ['2', '1'])
  store.observe('two', call(1))
  store.observe('one', call(6, 'touch'))
  store.observe('three', call(1))
  assert.equal(store.snapshot('two').total, 0)
  assert.equal(store.snapshot('one').running, 1)
})
await test('active capacity reports incomplete observations rather than inventing a settlement', () => {
  const store = createActivityStore({ maxActive: 1 })
  store.observe('one', call(1, 'first'))
  store.observe('one', call(2, 'omitted'))
  store.observe('one', result(3, 'omitted'))
  assert.equal(store.snapshot('one').limited, true)
  assert.equal(store.snapshot('one').total, 1)
  assert.equal(store.snapshot('one').running, 1)
  store.observe('one', result(4, 'first'))
  assert.equal(store.snapshot('one').running, 0)
  store.observe('one', call(5, 'next'))
  assert.equal(store.snapshot('one').total, 2)
})
await test('unpaired results, foreign names, malformed envelopes and wrong PTC pairs are ignored', () => {
  const store = createActivityStore()
  assert.equal(store.observe('one', result(1)), false)
  assert.equal(store.observe('one', call(2, 'a', 'ops_malicious')), false)
  assert.equal(store.observe('', call(3)), false)
  assert.equal(store.observe('one', { ...call(4), seq: NaN }), false)
  assert.equal(store.observe('one', { ...call(5), time: Infinity }), false)
  assert.equal(store.observe('one', null), false)
  store.observe('one', dispatch(6, 'child', 'ops_grep'))
  assert.equal(store.observe('one', dispatch(7, 'child', 'ops_glob', {})), false)
  assert.equal(store.snapshot('one').running, 1)
  store.observe('one', dispatch(8, 'child', 'ops_grep', {}))
  assert.equal(store.snapshot('one').running, 0)
})
await test('wall-clock regression never gives a negative observed duration', () => {
  const store = createActivityStore()
  store.observe('one', { ...call(1), time: 20 })
  store.observe('one', { ...result(2), time: 10 })
  assert.equal(store.snapshot('one').recent[0].durationMs, 0)
})
await test('subscriptions and disposal cannot interfere with tool or other observer state', () => {
  const store = createActivityStore()
  let updates = 0
  store.subscribe(() => { throw new Error('observer only') })
  const off = store.subscribe(() => updates++)
  store.observe('one', call(1)); assert.equal(updates, 1)
  off(); off(); store.observe('one', result(2)); assert.equal(updates, 1)
  store.dispose(); store.dispose()
  assert.equal(store.snapshot('one').total, 0)
  assert.equal(store.observe('one', call(3)), false)
})
await test('projection limits reject invalid or unbounded retention', () => {
  for (const options of [{ recentLimit: 0 }, { maxSessions: 257 }, { maxActive: 1.5 }]) {
    assert.throws(() => createActivityStore(options), /must be an integer/)
  }
})
